def _gather_candidates() -> list:
    candidates = discover_candidates()
    unseen = [item for item in candidates if not history.is_used(KEY, item.get("link"))]
    print(f"[논문] 전체 {len(candidates)}편 중 미작성 {len(unseen)}편")
    return unseen

